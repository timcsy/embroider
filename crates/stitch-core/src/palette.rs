//! 線色色票：給使用者看的中文色名與對應的顏色。前端的色票必須與這份一致（有測試檢查）。

use crate::ThreadColor;

const THREADS: [(u8, u8, u8, &str); 16] = [
    (200, 30, 40, "正紅"),
    (240, 150, 175, "粉紅"),
    (235, 120, 35, "橘色"),
    (250, 220, 80, "鵝黃"),
    (210, 165, 40, "金黃"),
    (80, 160, 60, "草綠"),
    (25, 95, 65, "墨綠"),
    (110, 185, 230, "天藍"),
    (40, 80, 180, "寶藍"),
    (25, 40, 100, "深藍"),
    (130, 70, 150, "紫色"),
    (120, 25, 50, "酒紅"),
    (120, 75, 45, "咖啡"),
    (140, 140, 145, "灰色"),
    (240, 230, 205, "米白"),
    (30, 30, 30, "黑色"),
];

pub fn threads() -> Vec<ThreadColor> {
    THREADS
        .iter()
        .map(|&(r, g, b, name)| ThreadColor::new(r, g, b, name))
        .collect()
}
